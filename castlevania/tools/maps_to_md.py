#!/usr/bin/env python3
"""Convert recorded inter-block maps to SGDK data (src/maps.c, inc/maps.h).

Uses the SNES port's map palette 09 and the recorded NES scroll, markers,
Simon poses and footstep requests. The generated data includes both arts.
"""
import argparse
import json
import re
from pathlib import Path
from art import ART_SUFFIX, md_word, nes_index
from decode_rooms import Rom
from screens_to_md import convert


def chr_origin(prg, snapshot):
    rom = Rom(b"NES\x1a" + bytes((8, 0, 0x21, 0)) + bytes(8) + prg)
    origin = {}
    # Common gameplay sprites/font, then the map's background overlay ($FD23).
    for load_set in (3, 2):
        pointer = rom.word(0xFDBB + 2 * load_set)
        while rom.rd(pointer) != 0xFF:
            bank = rom.rd(pointer)
            source, target, size = (rom.word(pointer + k) for k in (1, 3, 5))
            if target % 16 or size % 16 or target + size > len(snapshot):
                raise ValueError("invalid map CHR load list")
            for k in range(0, size, 16):
                tile = bytes(rom.rd(source + k + i, bank) for i in range(16))
                if snapshot[target + k:target + k + 16] == tile:
                    origin[(target + k) // 16] = (bank, (source + k) & 0x3FFF)
            pointer += 7
    return origin


def generate(root, recording):
    data_dir = root / "tools/extracted/maps"
    scenes = recording["scenes"]
    if [s["stage"] for s in scenes] != [4, 7, 10, 13, 16]:
        raise ValueError("expected the five post-boss map scenes")
    info = dict(frames=[f["sprites"] for s in scenes for f in s["frames"]],
                extra_cells=[cell for s in scenes for column in s["columns"] for cell in column])
    # Translate the gameplay HUD into this atlas so it can stay fixed in the
    # window plane and display the real score/health/weapon, not captured values.
    layout = json.loads((root / "tools/extracted/fixed_layout.json").read_text())
    level_source = (root / "src/level.c").read_text()
    def values(name):
        body = re.search(r"const u16 " + name + r"\[.*?\] = \{(.*?)\};", level_source, re.S)[1]
        return [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]
    def bg_key(word):
        tile = layout[word & 2047]
        if tile[0] != "bg":
            raise ValueError("HUD background is not a background tile")
        return tuple(tile[1:])
    hud_names = ("level_hud", "hud_digit", "hud_digit_lives", "hud_bar", "hud_ebar")
    hud_arrays = {name: values(name) for name in hud_names}
    info["extra_cells"] += [bg_key(word) for array in hud_arrays.values() for word in array]
    weapon_poses = []
    for pose in (5, 27, 32, 37, 40):     # dagger, holy water, axe, cross, watch
        body = re.search(r"static const SimonSprite obj_" + str(pose) + r"\[.*?\] = \{(.*?)\};", level_source, re.S)[1]
        sprites = []
        for dx, dy, attr, tile in re.findall(r"\{(-?\d+), (-?\d+), (0x[0-9A-Fa-f]+), (\d+)\}", body):
            raw = layout[int(tile)]
            if raw[0] == "bg":
                raise ValueError("HUD sprite is not a sprite tile")
            sprites.append((int(dx), int(dy), int(attr, 0), tuple(raw)))
        weapon_poses.append(sprites)
    info["extra_sprites"] = [raw for sprites in weapon_poses for _, _, _, raw in sprites]
    prg = (root / "tools/extracted/prg.bin").read_bytes()
    snapshot = (data_dir / "map_chr.bin").read_bytes()
    converted, stats = convert("map", info, data_dir, root / "tools/extracted/snes", prg,
                               chr_origin(prg, snapshot))
    print(stats)
    frame_records, column_records, scene_records = [], [], []
    frame_index = 0
    for scene in scenes:
        first_column, first_frame = len(column_records), len(frame_records)
        for column in scene["columns"]:
            column_records.append([converted["words"][tuple(cell)] for cell in column])
        for frame in scene["frames"]:
            requests = frame["sounds"]
            if len(requests) > 1 or any(s != 6 for s in requests):
                raise ValueError("unexpected map audio request")
            frame_records.append((frame["scroll"], converted["frames"][frame_index], bool(requests)))
            frame_index += 1
        scene_records.append((scene["stage"], first_column, len(scene["columns"]), first_frame, len(scene["frames"])))
    assert len(converted["tiles"]) + 16 < 2048
    src = root / "src/maps.c"
    with src.open("w") as f:
        f.write('// generated by tools/maps_to_md.py - do not edit\n#include "maps.h"\n\n')
        for k, art in enumerate(converted["arts"]):
            suffix = ART_SUFFIX[art]
            f.write(f'const u32 castle_map_tiles{suffix}[{len(converted["tiles"]) * 8}] = {{\n')
            for tile in converted["tiles"]:
                f.write('    ' + ', '.join(f'0x{v:08X}' for v in tile[k]) + ',\n')
            f.write('};\n')
            f.write(f'const u16 castle_map_palette{suffix}[64] = {{' + ', '.join(f'0x{md_word(c):04X}' for c in converted["colors"][k]) + '};\n')
            if art == "nes":
                f.write('const u8 castle_map_palette_nesidx[64] = {' + ', '.join(str(nes_index(c)) for c in converted["colors"][k]) + '};\n')
        for name, array in hud_arrays.items():
            export = "castle_map_hud" if name == "level_hud" else "castle_map_" + name
            translated = [converted["words"][bg_key(word)] for word in array]
            f.write(f'const u16 {export}[{len(array)}] = {{' + ', '.join(f'0x{v:04X}' for v in translated) + '};\n')
        f.write('const ScreenSprite castle_map_weapons[5][2] = {\n')
        for sprites in weapon_poses:
            if len(sprites) != 2:
                raise ValueError("expected two-tile weapon icon")
            entries = []
            for dx, dy, attr, raw in sprites:
                word = converted["sprite_words"][raw] | (attr & 0x1800)
                entries.append(f'{{{dx}, {dy}, 0x{word:04X}}}')
            f.write('    {' + ', '.join(entries) + '},\n')
        f.write('};\n')
        f.write(f'const u16 castle_map_columns[{len(column_records)}][30] = {{\n')
        for column in column_records:
            f.write('    {' + ', '.join(f'0x{v:04X}' for v in column) + '},\n')
        f.write('};\n')
        f.write(f'const ScreenSprite castle_map_sprites[{len(converted["entries"])}] = {{\n')
        for x, y, word in converted["entries"]:
            f.write(f'    {{{x}, {y}, 0x{word:04X}}},\n')
        f.write('};\n')
        f.write(f'const ScreenList castle_map_lists[{len(converted["lists"])}] = {{\n')
        for start, size in converted["lists"]:
            f.write(f'    {{{start}, {size}}},\n')
        f.write('};\n')
        f.write(f'const CastleMapFrame castle_map_frames[{len(frame_records)}] = {{\n')
        for scroll, sprites, sound in frame_records:
            f.write(f'    {{{scroll}, {sprites}, {int(sound)}}},\n')
        f.write('};\n')
        f.write(f'const CastleMapScene castle_map_scenes[{len(scene_records)}] = {{\n')
        for scene in scene_records:
            f.write('    {' + ', '.join(map(str, scene)) + '},\n')
        f.write('};\n')
    (root / "inc/maps.h").write_text(f'''// generated by tools/maps_to_md.py - do not edit
#ifndef CASTLE_MAPS_H
#define CASTLE_MAPS_H
#include "screens.h"
#define CASTLE_MAP_TILES {len(converted['tiles'])}
#define CASTLE_MAP_SCENES {len(scene_records)}
typedef struct {{ u16 scroll, sprites; u8 footstep; }} CastleMapFrame;
typedef struct {{ u16 stage, column, columns, frame, frames; }} CastleMapScene;
extern const u32 castle_map_tiles[];
extern const u32 castle_map_tiles_nes[];
extern const u16 castle_map_palette[64];
extern const u16 castle_map_palette_nes[64];
extern const u8 castle_map_palette_nesidx[64];
extern const u16 castle_map_hud[160];
extern const u16 castle_map_hud_digit[10];
extern const u16 castle_map_hud_digit_lives[10];
extern const u16 castle_map_hud_bar[3];
extern const u16 castle_map_hud_ebar[3];
extern const ScreenSprite castle_map_weapons[5][2];
extern const u16 castle_map_columns[][30];
extern const ScreenSprite castle_map_sprites[];
extern const ScreenList castle_map_lists[];
extern const CastleMapFrame castle_map_frames[];
extern const CastleMapScene castle_map_scenes[CASTLE_MAP_SCENES];
#endif
''')
    print(f"{len(frame_records)} frames, {len(column_records)} panorama columns; wrote {src}")
    return converted


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args()
    generate(args.root, json.loads((args.root / "tools/extracted/maps/maps.json").read_text()))


if __name__ == "__main__":
    main()

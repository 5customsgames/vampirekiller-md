#!/usr/bin/env python3
"""Convert a nes_dump.py snapshot into SGDK data (src/scene.c + inc/scene.h).

usage: nes_to_md.py <snapshot dir> [--src DIR] [--inc DIR]

Colour model: NES palette k, colour c becomes MD palette index 4*k+c, so every NES 4-colour palette
lives inside one 16-colour MD palette. Background tiles use MD PAL0, sprites use MD PAL1.
Screen geometry: the 256x240 NES picture is centred on the 320x224 MD screen (x + 32, y - 8).
Run with the venv python that has py65 (it imports the NES colour table from nes_dump.py).
"""
import argparse, json
from pathlib import Path
from nes_dump import NES_RGB, tile_pixels

OX, OY = 32, -8


def md_color(nes_index):
    c = NES_RGB[nes_index & 0x3F]
    r, g, b = [min(7, (((c >> s) & 255) + 16) >> 5) for s in (16, 8, 0)]
    return (b << 9) | (g << 5) | (r << 1)


def md_tile(rows, pal):
    """8x8 rows of NES 2-bit pixels -> 8 u32 (4bpp, leftmost pixel in the high nibble)."""
    out = []
    for row in rows:
        v = 0
        for c in row:
            v = (v << 4) | (0 if c == 0 else pal * 4 + c)
        out.append(v)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("snap")
    root = Path(__file__).resolve().parent.parent
    ap.add_argument("--src", default=str(root / "src"))
    ap.add_argument("--inc", default=str(root / "inc"))
    a = ap.parse_args()
    d = Path(a.snap)
    chr_, nt, pal, oam = [(d / f).read_bytes() for f in ("chr.bin", "nametables.bin", "palette.bin", "oam.bin")]
    st = json.loads((d / "state.json").read_text())
    ctrl = st["ctrl"]
    bgbase = 0x1000 if ctrl & 0x10 else 0
    assert ctrl & 0x20, "expected 8x16 sprites"

    # --- background: 64x30 cells (both nametables side by side) ---
    tiles, index, cells = [], {}, []
    for ty in range(30):
        for n in range(2):
            for tx in range(32):
                base = n * 1024
                t = nt[base + ty * 32 + tx]
                attr = nt[base + 960 + (ty // 4) * 8 + tx // 4]
                p = (attr >> (((ty // 2) & 1) * 4 + ((tx // 2) & 1) * 2)) & 3
                key = (t, p)
                if key not in index:
                    index[key] = len(tiles)
                    tiles.append(md_tile(tile_pixels(chr_, bgbase, t), p))
                cells.append(index[key])
    nbg = len(tiles)

    # --- sprites (8x16, two tiles per MD sprite, top tile first) ---
    sprites, sidx = [], {}
    sprite_list = []
    for s in range(1, 64):  # entry 0 is the sprite-0 hit marker
        y, t, at, x = oam[s * 4:s * 4 + 4]
        if y >= 0xEF:
            continue
        base = 0x1000 if t & 1 else 0
        top = t & 0xFE
        p = at & 3
        key = (base, top, p)
        if key not in sidx:
            sidx[key] = nbg + len(sprites)
            sprites += [md_tile(tile_pixels(chr_, base, top), p), md_tile(tile_pixels(chr_, base, top + 1), p)]
        attr = (1 << 13) | ((at & 0x80) << 4) | ((at & 0x40) << 5)  # PAL1, vflip bit 12, hflip bit 11
        sprite_list.append((x + OX, y + 1 + OY, attr, sidx[key]))

    all_tiles = tiles + sprites
    colors = [md_color(pal[0] if c % 4 == 0 else pal[c]) for c in range(16)]
    colors += [md_color(pal[0] if c % 4 == 0 else pal[16 + c]) for c in range(16)]
    colors[16] = md_color(pal[0])
    total_x = (ctrl & 1) * 256 + st["scroll_x"]

    # HUD rows 1..5 come from the nametable that is currently selected
    hud_nt = ctrl & 1
    hud = [cells[ty * 64 + hud_nt * 32 + tx] for ty in range(1, 6) for tx in range(32)]

    src = Path(a.src)
    src.mkdir(exist_ok=True)
    Path(a.inc).mkdir(exist_ok=True)
    with open(src / "scene.c", "w") as f:
        f.write("// generated by tools/nes_to_md.py - do not edit\n#include \"scene.h\"\n\n")
        f.write(f"const u32 scene_tiles[{len(all_tiles) * 8}] = {{\n")
        for t in all_tiles:
            f.write("    " + ", ".join(f"0x{v:08X}" for v in t) + ",\n")
        f.write("};\n\n")
        f.write(f"const u16 scene_map[{len(cells)}] = {{\n")
        for r in range(30):
            f.write("    " + ", ".join(str(c) for c in cells[r * 64:(r + 1) * 64]) + ",\n")
        f.write("};\n\n")
        f.write(f"const u16 scene_hud[{len(hud)}] = {{\n")
        for r in range(5):
            f.write("    " + ", ".join(str(c) for c in hud[r * 32:(r + 1) * 32]) + ",\n")
        f.write("};\n\n")
        f.write("const u16 scene_palette[32] = {" + ", ".join(f"0x{c:04X}" for c in colors) + "};\n\n")
        f.write(f"const SceneSprite scene_sprites[{max(1, len(sprite_list))}] = {{\n")
        for x, y, attr, tile in sprite_list:
            f.write(f"    {{{x}, {y}, 0x{attr:04X}, {tile}}},\n")
        if not sprite_list:
            f.write("    {0, 0, 0, 0},\n")
        f.write("};\n")
    with open(Path(a.inc) / "scene.h", "w") as f:
        f.write(f"""// generated by tools/nes_to_md.py - do not edit
#ifndef SCENE_H
#define SCENE_H
#include <genesis.h>

typedef struct {{ s16 x, y; u16 attr; u16 tile; }} SceneSprite;

#define SCENE_TILE_COUNT   {len(all_tiles)}
#define SCENE_SPRITE_COUNT {len(sprite_list)}
#define SCENE_SCROLL_X     {total_x}

extern const u32 scene_tiles[];
extern const u16 scene_map[];
extern const u16 scene_hud[];
extern const u16 scene_palette[32];
extern const SceneSprite scene_sprites[];

#endif
""")
    print(f"{nbg} bg tiles + {len(sprites)} sprite tiles, {len(sprite_list)} sprites, scroll_x={total_x}")


if __name__ == "__main__":
    main()

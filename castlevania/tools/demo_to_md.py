#!/usr/bin/env python3
"""Copy the NES game's demo inputs (the title's attract mode) into SGDK data.

usage: demo_to_md.py <rom.nes>

When the title has waited 652 frames (NES state 1 for 140 frames, then 512 more) the game plays a demo (state 2),
the next one each time ($F3). Its routine at $FEB3 (fixed bank) reads the demo's stream from bank 5, through the
pointer table at $FF24 + 2 * $F3: records of three bytes, frames, the buttons pressed on the first frame ($F5) and
the buttons held ($F7), each byte with A $80, B $40, SELECT $20, START $10, UP 8, DOWN 4, LEFT 2, RIGHT 1. Each demo
ends with a frame of every button pressed ($FF): START, which ends a demo as the player's would, and the title comes
back. The stream is read on the game's play frames only (not while a room loads).
The stages come from the NES game's RAM ($28) while the demos play: 12, 7 and 8 (measured).

Writes src/demo.c and inc/demo.h (generated, not in git).
"""
import sys
from pathlib import Path

STAGES = [12, 7, 8]


def main():
    root = Path(__file__).resolve().parent.parent
    rom = Path(sys.argv[1]).read_bytes()
    fixed = lambda a: rom[16 + 7 * 0x4000 + a - 0xC000]
    bank5 = lambda a: rom[16 + 5 * 0x4000 + a - 0x8000]
    demos = []
    for k, stage in enumerate(STAGES):
        p = fixed(0xFF24 + 2 * k) | fixed(0xFF25 + 2 * k) << 8
        data = []
        while bank5(p + 1) != 0xFF:
            assert bank5(p) and bank5(p) != 0xFF, "a record of 0 frames"
            data += [bank5(p), bank5(p + 1), bank5(p + 2)]
            p += 3
        demos.append((stage, data + [0xFF]))          # 0xFF: the START frame
        print(f"demo {k}: stage {stage}, {len(data) // 3} records, {sum(data[0::3])} frames")
    with open(root / "src/demo.c", "w") as f:
        f.write("// generated by tools/demo_to_md.py - do not edit\n#include \"demo.h\"\n\n")
        for stage, data in demos:
            f.write(f"const u8 demo_stage{stage}[{len(data)}] = {{\n")
            for i in range(0, len(data), 24):
                f.write("    " + ",".join(str(v) for v in data[i:i + 24]) + ",\n")
            f.write("};\n")
    with open(root / "inc/demo.h", "w") as f:
        f.write("// generated by tools/demo_to_md.py - do not edit\n#ifndef DEMO_H\n#define DEMO_H\n#include <genesis.h>\n\n"
                "// records: frames, NES buttons pressed on the first frame, NES buttons held; 0xFF: START, the demo ends\n")
        for stage, _ in demos:
            f.write(f"extern const u8 demo_stage{stage}[];\n")
        f.write("\n#endif\n")


if __name__ == "__main__":
    main()

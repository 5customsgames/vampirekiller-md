#!/usr/bin/env python3
"""Convert the Wilhelm scream to a short mono signed 8-bit SGDK PCM resource."""
from pathlib import Path
import argparse,subprocess,json,hashlib,wave

def convert(source,out):
    rate=22050;duration=1.58;fade=.03
    process=subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-i',str(source),
        '-t',str(duration),'-af',f'volume=0.9,afade=t=in:d=0.003,afade=t=out:st={duration-fade}:d={fade},aresample=22050:dither_method=triangular',
        '-ac','1','-ar',str(rate),'-c:a','pcm_s8','-f','s8','pipe:1'],capture_output=True,check=True)
    samples=round(duration*rate);raw=process.stdout[:samples].ljust(samples,b'\0');data=raw+b'\0'*(-len(raw)%256)
    out.mkdir(parents=True,exist_ok=True);(out/'wilhelm.pcm').write_bytes(data)
    with wave.open(str(out/'wilhelm-preview.wav'),'wb') as w:
        w.setparams((1,1,rate,0,'NONE','not compressed'));w.writeframes(bytes(x^128 for x in data))
    info=dict(source_page='https://commons.wikimedia.org/wiki/File:Wilhelm_Scream.ogg',
        source_url='https://upload.wikimedia.org/wikipedia/commons/d/d9/Wilhelm_Scream.ogg',
        source_license='CC0, as indicated on the Commons file page',
        source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),sha256=hashlib.sha256(data).hexdigest(),
        rate=rate,channels=1,bits=8,signed=True,samples=samples,bytes=len(data),seconds=len(data)/rate,loop=False,alignment=256)
    (out/'wilhelm.json').write_text(json.dumps(info,indent=2)+'\n')
    (out.parent/'wilhelm_audio.h').write_text('// Generated resource declaration; regenerated by ResComp.\n#ifndef CASTLEVANIA_WILHELM_AUDIO_H\n#define CASTLEVANIA_WILHELM_AUDIO_H\nextern const u8 wilhelm_pcm['+str(len(data))+'];\n#endif\n')
    return info
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('--out',type=Path,default=Path(__file__).resolve().parents[1]/'res/audio');a=p.parse_args()
    print(json.dumps(convert(a.source,a.out),indent=2))

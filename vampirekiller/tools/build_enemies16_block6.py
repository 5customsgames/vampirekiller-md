#!/usr/bin/env python3
"""Common enemies of block 6 (stages 16 and 17, not the stage 17 boss room and not the stage 18) in the 16-bit art
(research/gfx16.md, section "Ennemis 16 bits (bloc 6)").

usage: build_enemies16_block6.py <castlevania-md checkout> [--preview FILE.png] [--board FILE.png] [--orient]

Same method as tools/build_enemies16_block5.py: the code, the sprite table, the hit boxes and the VRAM cells stay those of the
MSX port, only the picture of the cells changes. Stages 16 to 18 use the late enemy system (late_graphics.inc, generated by
tools/build_late_graphics.py): a room loads the pool cells of its enemies, one transfer per run of consecutive pool slots
(`late_graphics_slots`). The 16-bit pictures are stored in an array indexed by that same pool slot (vk_enemy16b6_cells: slot N
is the 128 bytes at 128 * N), so a room of stage 16 or 17 loads the same slots with the same transfers from this array instead
of late_graphics_words: same tile count, same frames. Stage 18 (same pool, other rooms) is not touched.

- Late enemy types of stages 16 and 17 (`internal` type of the cell, SAT in enemies.c / enemies_type12.inc / enemies_stage11.inc):
    stage 16, raw 12h (internal 23)  the big bat that hovers, aims and fires: 4 sprites, pose 4E (wings spread) = cells 40 48 58 in
                          a row (48 x 16) + body 50 under the middle one, pose 4F (wings folded) = 60 68 + body 70 (32 x 32);
                          the same body as the stage 3 boss, drawn with the same pictures (obj_51, obj_52 of Castlevania-MD)
    stage 16, raw 01 shot (internal 10)  its fireball, pool slot 3 (cells 60 and F0, one 8 x 8 sprite): red sphere
    stage 17, raw 0B (internal 11) + its bone (internal 13), raw 0D (internal 14) flea, raw 10 (internal 20) + its axe (internal
                          21): the cells of the late pool slots 26 to 66, as in block 5 (same poses, same cells)
    stage 17, raw 0F (internal 18)  eagle (rooms 7 and 10, with its flea): MSX head 40 + wing columns 48/50 (6D), 58/60 (6E), 68/70 (8D); 16-bit: left
                          column 40/44 (6D, 8D), 4C/54 (6E) + wing column, as the stage 11 eagle (block 4); 44, 4C, 54 are pool slots
                          81 to 83, loaded after the eagle's slot 80 in the same transfer (actors.c, 16-bit mode only)
    object 1B (internal 15, slots 4 and 5): kept MSX.
- Pictures (Castlevania-MD): block 6 (src/block6.c: b6_skel0/1 = the skeleton, b6_bone0/1/2, b6_flea_stand/jump; the block 6 "knight"
  is a skeleton too), the axe knight and its axe come from block 5 (b5_axek, b5_kaxe: block 6 has none), the eagle from block 4
  (b4_eagle0/1: the ravens of block 6 are 16 x 16 and would be half the size of the MSX eagle's hit box), the bat from level.c
  (obj_51, obj_52). Facing left like the MSX left cells; the right cells are their mirror.
- Palette: as in blocks 1 to 5 the entries other PAL2 content reads (1, 2, 3, 7, 8, 12, 13, 14, 15) keep their MSX colour. Entry 7
  is 66C (stage 16, stage 17 but rooms 3 to 5) or 26C (stage 17 rooms 3 to 5). Four palettes, one per group of rooms, each with the
  colours of the enemies of the group only: [0] stage 16 (bat), [1] stage 17 room 1 (skeleton, bone), [2] stage 17 rooms 2 and 6 to 10
  (flea, eagle: the flea cells are shared by the rooms with and without the eagle), [3] stage 17 rooms 3 to 5 (axe knight, axe).
"""
import functools
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_enemies16 as B  # noqa: E402
import build_candle16 as C16  # noqa: E402
import build_enemies16_block2 as T  # noqa: E402
import build_enemies16_block4 as T4  # noqa: E402
import build_enemies16_block5 as T5  # noqa: E402
import build_items16 as I  # noqa: E402

ROOT = B.ROOT
GEN = B.GEN
STAGES = (16, 17)
SLOTS = 84                                   # pool slots 0 .. 83 are stored (stages 16 and 17 use 3 to 5 and 26 to 80; 81 to 83: EAGLE_EXTRA)
EAGLE_EXTRA = {(18, 0x44): 81, (18, 0x4C): 82, (18, 0x54): 83}   # left column cells of the 16-bit eagle that the MSX tables do not load
VARIABLE = 7                                 # the fixed entry whose MSX colour differs between the rooms
GROUPS = 4                                   # palettes: stage 16 / stage 17 room 1 / rooms 2 6-10 / rooms 3-5
KIND = {23: 'bat', 10: 'bat', 11: 'skel', 13: 'skel', 14: 'flea', 18: 'eagle', 20: 'axe', 21: 'axe'}   # internal type -> enemy
GROUP_OF_KIND = {'bat': 0, 'skel': 1, 'flea': 2, 'eagle': 2, 'axe': 3}
GROUP_KINDS = {g: [k for k, v in GROUP_OF_KIND.items() if v == g] for g in range(GROUPS)}
BALL = T5.BALL
SPHERE = T4.SPHERE                           # the red sphere of the dragon shot of block 4 (8 x 8)
FREE = B.FREE


def group_of(stage, room):
    """The palette of a room: the choice of vk_gfx16_pal2 (gfx16.c)."""
    return 0 if stage == 16 else 1 if room == 1 else 3 if 3 <= room <= 5 else 2


# ---- the late pool -------------------------------------------------------------------------------------------

@functools.lru_cache(maxsize=None)
def enemy_rooms():
    """{(stage, room): [(type, pattern, slot)]} of the rooms of stages 16 and 17 that load cells."""
    rooms, cells, slots = T5.late_tables()
    out = {}
    for s in STAGES:
        for r in range(12):
            first, tiles, cf, n = rooms[(s - 12) * 12 + r]
            if tiles:
                sl = slots[first:first + tiles // 4]
                out[(s, r)] = [(ty, p, sl[c]) for ty, p, c in cells[cf:cf + n]]
    return out


@functools.lru_cache(maxsize=None)
def slot_map():
    """{(type, pattern): slot} over the rooms of stages 16 and 17 (checked: one slot per cell)."""
    where = {}
    for lst in enemy_rooms().values():
        for ty, p, slot in lst:
            assert where.setdefault((ty, p), slot) == slot, (ty, p)
    return where


@functools.lru_cache(maxsize=None)
def room_info():
    """{(stage, room): (MSX palette, group, set of enemy kinds)} of the rooms that take a vk_enemy16b6_palette: those with an
    enemy of the block (a room that loads only object 1B stays MSX)."""
    pal = T5.msx_palettes()
    info = {}
    for (s, r), lst in enemy_rooms().items():
        kinds = {KIND[ty] for ty, _, _ in lst if ty in KIND}
        if not kinds:
            continue
        gs = {GROUP_OF_KIND[k] for k in kinds}
        assert gs == {group_of(s, r)}, (s, r, kinds)
        info[(s, r)] = (pal(s, r), group_of(s, r), kinds)
    return info


@functools.lru_cache(maxsize=None)
def group_fixed():
    """{group: ({entry: MSX colour} of the fixed entries but 7, MSX entry 7)}: the same in every room of the group (checked)."""
    out = {}
    for g in range(GROUPS):
        pals = [p for p, gg, k in room_info().values() if gg == g]
        for p in pals:
            assert [p[i] for i in B.FIXED] == [pals[0][i] for i in B.FIXED], ('fixed MSX colours differ in group', g)
        out[g] = ({i: pals[0][i] for i in B.FIXED if i != VARIABLE}, pals[0][VARIABLE])
    return out


# ---- pictures --------------------------------------------------------------------------------------------------

def jobs(b6, b5, b4, cv):
    """[dict(name, img, mode, size, cells=[(type, pattern, x, y)], blanks=[(type, pattern)], ref, kind)]

    `img` is laid on the canvas against the MSX picture of `ref` (composite of the layers, default `cells` + `blanks` at the
    place of the cell they pair with); `cells` receive the picture, `blanks` are written blank (second layer). With mode None
    `img` is already the canvas (`size`) and the cells are windows of it."""
    out = []

    def job(name, img, mode, size, ty, cells, blanks=(), kind=None, ref=None, crop=True):
        if mode and crop:
            img = B.crop(img)
        cs = [(ty, p, x, y) for p, x, y in cells]
        bl = [(ty, p) for p in blanks]
        rf = ref or cs + [(ty, p, x, y) for p, (_, x, y) in zip(blanks, cells * 2)]
        out.append(dict(name=name, img=img, mode=mode, size=size, cells=cs, blanks=bl, ref=rf, kind=kind or KIND[ty]))

    def both(name, img, mode, size, ty, left, right, **kw):
        job(name, img, mode, size, ty, left[0], left[1], crop=True, **kw)
        job(name + ' R', B.mirror(B.crop(img)), mode, size, ty, right[0], right[1], crop=False, **kw)

    def column(base):
        return ([(base, 0, 0), (base + 8, 0, 16)], [base + 4, base + 12])

    # stage 16: raw 12h, pose 4E / 4F (cells 40 48 58 + body 50, 60 68 + body 70), pictures of the stage 3 boss (same body)
    for name, obj, size, cells in (('bat4E', 51, (48, 32), [(0x40, 0, 0), (0x48, 16, 0), (0x58, 32, 0), (0x50, 16, 16)]),
                                   ('bat4F', 52, (32, 32), [(0x60, 0, 0), (0x68, 16, 0), (0x70, 8, 16)])):
        img = cv.pose(obj)
        assert (len(img[0]), len(img)) == size
        covered = {(x + i, y + j) for _, x, y in cells for i in range(16) for j in range(16)}
        assert not [1 for j, r in enumerate(img) for i, p in enumerate(r) if p is not None and (i, j) not in covered], name
        job(name, img, None, size, 23, cells)
    # its fireball: cells 60 and F0 of the pool slot 3 (internal 10)
    for p in (0x60, 0xF0):
        job('fire%02X' % p, I.sphere(SPHERE, 8), 'centre', (16, 16), 10, [(p, 0, 0)])
    # stage 17: raw 09-like columns do not exist here; raw 0B skeleton 47 48 left (64 / 68, 6C / 70), 49 4A right (74 / 78, 7C / 80)
    for k, (left, right) in enumerate(((0x64, 0x74), (0x6C, 0x7C))):
        both('skel%d' % k, b6.sprite('b6_skel%d' % k), 'feet', (16, 32), 11, ([(left, 0, 0), (left + 4, 0, 16)], []),
             ([(right, 0, 0), (right + 4, 0, 16)], []))
    # its bone: 4B upright, 4C /, 4D \ ; pose 3 = the white ball F0
    for k, p in enumerate((0x98, 0x9C, 0xA0)):
        job('bone%d' % k, b6.sprite('b6_bone%d' % k), 'centre', (16, 16), 13, [(p, 0, 0)])
    job('ball_bone', I.sphere(BALL['bone'], 8), 'centre', (16, 16), 13, [(0xF0, 0, 0)], kind='skel')
    # flea: 67 / 6A stand, 68 / 6B jump
    both('flea_stand', b6.sprite('b6_flea_stand'), 'feet', (16, 16), 14, ([(0x80, 0, 0)], []), ([(0x88, 0, 0)], []))
    both('flea_jump', b6.sprite('b6_flea_jump'), 'feet', (16, 16), 14, ([(0x84, 0, 0)], []), ([(0x8C, 0, 0)], []))
    # eagle (as block 4): the whole 32 x 32 picture of each pose on four cells, left column + wing column (the MSX head 40 shared
    # by the poses froze the left wing). Left cells 40 / 44 (6D, 8D) and 4C / 54 (6E): 40 is the MSX head cell, 44, 4C and 54 are
    # EAGLE_EXTRA, appended to the run of the eagle's pool slots (actors.c loads them in the same transfer in 16-bit mode)
    e0, e1 = b4.sprite('b4_eagle0'), b4.sprite('b4_eagle1')
    assert len(e0) == len(e1) == 32 and len(e0[0]) == len(e1[0]) == 32
    for name, img, left, (top, bottom) in (('eagle6D', e0, (0x40, 0x44), (0x48, 0x50)), ('eagle6E', e1, (0x4C, 0x54), (0x58, 0x60)),
                                           ('eagle8D', e0, (0x40, 0x44), (0x68, 0x70))):
        job(name, img, None, (32, 32), 18, [(left[0], 0, 0), (left[1], 0, 16), (top, 16, 0), (bottom, 16, 16)])
    # axe knight (block 5 art: 24 x 32 picture, shield cut, on a 16 x 32 pose): 5F 60 face left, 61 62 right
    for k, (left, right) in enumerate(((0x40, 0x60), (0x50, 0x70))):
        both('axek%d' % k, T5.AXE[k](b5), 'feet', (16, 32), 20, column(left), column(right))
    for k, base in enumerate((0x80, 0x88, 0x90, 0x98)):
        job('kaxe%d' % k, b5.sprite('b5_kaxe%d' % k), 'centre', (16, 16), 21, [(base, 0, 0)], [base + 4])
    job('ball_axe', I.sphere(BALL['axe'], 8), 'centre', (16, 16), 21, [(0xF0, 0, 0)])
    return out


# ---- laying the pictures on the MSX poses ------------------------------------------------------------------------

def msx_cell(ty, p):
    return B.Msx.cell(T5.pool_words(), slot_map()[(ty, p)])


def msx_canvas(j):
    return B.canvas_of([(x, y, msx_cell(ty, p)) for ty, p, x, y in j['ref']])


def laid(js):
    res = []
    for j in js:
        cw, ch = j['size']
        if j['mode'] is None:
            res.append((j, j['img'], None))
            continue
        ref = B.ref_box(msx_canvas(j))
        res.append((j, B.place(j['img'], cw, ch, ref, j['mode']), ref))
    return res


# ---- palettes --------------------------------------------------------------------------------------------------

def histograms(pics):
    """{kind: {colour: pixels}} over the cells written (each cell once)."""
    hist, seen = {}, set()
    for j, img, ref in pics:
        for ty, p, x, y in j['cells']:
            if (ty, p) in seen:
                continue
            seen.add((ty, p))
            h = hist.setdefault(j['kind'], {})
            for row in img[y:y + 16]:
                for c in row[x:x + 16]:
                    if c is not None:
                        h[c] = h.get(c, 0) + 1
    return hist


def build_palettes(pics):
    """Palettes [group] of 16 words, the entries each group's cells may use, the colour error per kind."""
    hist = histograms(pics)
    pals, allowed, errs = [], [], {}
    for g in range(GROUPS):
        fixed, seven = group_fixed()[g]
        base = [B.lvl(w) for w in fixed.values()] + [B.lvl(seven)]
        merged = {}
        for k in GROUP_KINDS[g]:
            for c, n in hist[k].items():
                merged[c] = merged.get(c, 0) + n
        free, _ = T5.optimise(len(FREE), lambda f: T5.err_of(merged, base + list(f)), merged)
        pal = [0] * 16
        for i, w in fixed.items():
            pal[i] = w
        pal[VARIABLE] = seven
        for i, col in zip(FREE, free):
            pal[i] = B.word(col)
        pals.append(pal)
        idx = sorted(set(fixed) | {VARIABLE} | set(FREE))
        allowed.append(idx)
        for k in GROUP_KINDS[g]:
            errs[k] = T5.err_of(hist[k], [B.lvl(pal[i]) for i in idx]) / sum(hist[k].values())
    return pals, allowed, errs, hist


# ---- cells -----------------------------------------------------------------------------------------------------

def build(b6, b5, b4, cv):
    pics = laid(jobs(b6, b5, b4, cv))
    pals, allowed, errs, hist = build_palettes(pics)
    words = T5.pool_words()
    smap = {**slot_map(), **EAGLE_EXTRA}
    pool = [[0] * 32 for s in range(SLOTS)]
    pool[4], pool[5] = C16.blob_b_cells()                       # object 1B (slots 4, 5): the 16-bit blob (build_candle16.py)
    written = {}
    for j, img, ref in pics:
        g = GROUP_OF_KIND[j['kind']]
        for ty, p, x, y in j['cells']:
            rows = [[0 if img[y + dy][x + dx] is None else T5.to_index(pals[g], img[y + dy][x + dx], allowed[g])
                     for dx in range(16)] for dy in range(16)]
            tiles = B.cell_tiles(rows)
            assert written.get((ty, p), tiles) == tiles, 'cell %d %02X written twice with other pixels' % (ty, p)
            written[(ty, p)] = tiles
            pool[smap[(ty, p)]] = tiles
        for ty, p in j['blanks']:
            assert written.get((ty, p), [0] * 32) == [0] * 32, 'cell %d %02X blank and drawn' % (ty, p)
            written[(ty, p)] = [0] * 32
            pool[smap[(ty, p)]] = [0] * 32
    # a pool slot shared by several (type, pattern): the 16-bit contents must agree
    by_slot = {}
    for key, s in smap.items():
        if key in written:
            assert by_slot.setdefault(s, written[key]) == written[key], ('slot %d shared with other pixels' % s, key)
    return pool, pals, allowed, errs, hist, written, pics


def write(pool, pals):
    h = ['/* Generated by tools/build_enemies16_block6.py (Castlevania-MD art, research/gfx16.md). Common enemies of stages 16',
         ' * and 17 in 16-bit mode, in the layout of the late enemy pool they replace. */',
         '#ifndef VK_ENEMIES16B6_MD_H', '#define VK_ENEMIES16B6_MD_H', '#include <genesis.h>',
         '/* PAL2 of those rooms: the MSX colours other content uses keep their entries; the free ones hold the 16-bit colours.',
         ' * One palette per group of rooms: [0] stage 16 (bat), [1] stage 17 room 1 (skeleton), [2] stage 17 rooms 2 and 6 to 10',
         ' * (flea, eagle), [3] stage 17 rooms 3 to 5 (axe knight). */',
         'extern const u16 vk_enemy16b6_palette[%d][16];' % GROUPS,
         '/* The late pool of the rooms of stages 16 and 17, in the order of late_graphics_words (cell N is the pool slot N of',
         ' * late_graphics_slots, 4 tiles of 8 words): slots 3 and 26 to 80 with the 16-bit pictures, slots 4 and 5 (object 1B) as',
         ' * they are, the others blank. */',
         '#define VK_ENEMY16B6_SLOTS %d' % SLOTS,
         'extern const u32 vk_enemy16b6_cells[%d];' % (SLOTS * 32),
         '#endif']
    c = ['/* Generated by tools/build_enemies16_block6.py. */', '#include "enemies16b6_md.h"',
         'const u16 vk_enemy16b6_palette[%d][16] = {\n%s\n};' % (GROUPS, ',\n'.join('{\n%s\n}' % B.fmt(p, 4) for p in pals)),
         'const u32 vk_enemy16b6_cells[%d] = {\n%s\n};' % (SLOTS * 32, B.fmt([w for cell in pool for w in cell], 8))]
    (GEN / 'enemies16b6_md.h').write_text('\n'.join(h) + '\n')
    (GEN / 'enemies16b6_md.c').write_text('\n'.join(c) + '\n')


def data_size():
    return SLOTS * 128 + GROUPS * 32


def rgb(pal):
    return [(0, 0, 0)] + [tuple(v * 36 for v in B.lvl(pal[i])) for i in range(1, 16)]


def preview(pool, pals, path):
    """For every enemy cell drawn: the MSX cell (palette of a room of its group) next to the 16-bit cell (palette of the group)."""
    from PIL import Image, ImageDraw
    S = 4
    smap = slot_map()
    room_of = {}
    for (s, r), (p, g, kinds) in room_info().items():
        room_of.setdefault(g, p)
    words = T5.pool_words()
    rows = []
    for (ty, p), slot in sorted(smap.items(), key=lambda kv: kv[1]):
        if ty not in KIND:
            continue
        g = GROUP_OF_KIND[KIND[ty]]
        rows.append(('t%d %02X g%d' % (ty, p, g), B.Msx.cell(words, slot), B.Msx.cell(pool[slot], 0), rgb(room_of[g]), rgb(pals[g])))
    cols = 6
    nrow = (len(rows) + cols - 1) // cols
    im = Image.new('RGB', (cols * (36 * S + 8), nrow * (18 * S + 14)), (90, 100, 120))
    d = ImageDraw.Draw(im)
    for n, (lab, a, b, pa, pb) in enumerate(rows):
        ox, oy = (n % cols) * (36 * S + 8), (n // cols) * (18 * S + 14)
        d.text((ox, oy), lab, fill=(255, 255, 255))
        for dx, px, mp in ((0, a, pa), (17 * S + 4, b, pb)):
            for y in range(16):
                for x in range(16):
                    if px[y][x]:
                        d.rectangle([ox + dx + x * S, oy + 12 + y * S, ox + dx + x * S + S - 1, oy + 12 + y * S + S - 1],
                                    fill=mp[px[y][x]])
    im.save(path)


def board(pool, pals, pics, path):
    """One row per pose: the MSX picture (palette of a room of the group), the 16-bit picture, and the 16-bit picture with the
    outline of the MSX silhouette (red) over it, on a mid grey and on a dark wall."""
    from PIL import Image, ImageDraw
    S = 4
    smap = slot_map()
    room_of = {}
    for (s, r), (p, g, kinds) in room_info().items():
        room_of.setdefault(g, p)
    cellw, cellh = 100 * S, 36 * S + 16
    cols = 3
    smap = {**slot_map(), **EAGLE_EXTRA}
    items = [(j, img) for j, img, ref in pics]
    nrow = (len(items) + cols - 1) // cols
    im = Image.new('RGB', (cols * (cellw + 6) + 6, nrow * cellh + 6), (110, 110, 120))
    d = ImageDraw.Draw(im)
    for n, (j, img) in enumerate(items):
        g = GROUP_OF_KIND[j['kind']]
        ox, oy = (n % cols) * (cellw + 6) + 4, (n // cols) * cellh + 4
        d.text((ox, oy), j['name'], fill=(255, 255, 255))
        cells = j['cells']
        new = B.canvas_of([(x, y, B.Msx.cell(pool[smap[(ty, p)]], 0)) for ty, p, x, y in cells])
        old = msx_canvas(j) if j['mode'] is not None else B.canvas_of([(x, y, msx_cell(ty, p)) for ty, p, x, y in cells if (ty, p) in slot_map()])
        mpal, npal = rgb(room_of[g]), rgb(pals[g])
        w, h = max(len(new[0]), len(old[0])), max(len(new), len(old))
        sil = {(x, y) for y, r in enumerate(old) for x, v in enumerate(r) if v}
        for k, (canv, pal, bg) in enumerate(((old, mpal, (70, 70, 80)), (new, npal, (70, 70, 80)), (new, npal, (150, 150, 160)))):
            bx = ox + k * (w * S + 8)
            d.rectangle([bx, oy + 12, bx + w * S - 1, oy + 12 + h * S - 1], fill=bg)
            for y, r in enumerate(canv):
                for x, v in enumerate(r):
                    if v:
                        d.rectangle([bx + x * S, oy + 12 + y * S, bx + x * S + S - 1, oy + 12 + y * S + S - 1], fill=pal[v])
            if k == 2:
                for (x, y) in sil:
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        if (x + dx, y + dy) not in sil:
                            d.rectangle([bx + x * S + (S - 1 if dx > 0 else 0), oy + 12 + y * S + (S - 1 if dy > 0 else 0),
                                         bx + x * S + (S - 1 if dx >= 0 else 0), oy + 12 + y * S + (S - 1 if dy >= 0 else 0)],
                                        fill=(255, 0, 0))
    im.save(path)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    b6, b5, b4, cv = T.Block(root, 6), T.Block(root, 5), T.Block(root, 4), B.CV(root)
    if '--orient' in sys.argv:
        for j, img, ref in laid(jobs(b6, b5, b4, cv)):
            if j['mode'] is None:
                continue
            m = B.mirror([r[:] for r in img])
            print('%-14s iou %.2f mirrored %.2f' % (j['name'], T5.iou(img, msx_canvas(j)), T5.iou(m, msx_canvas(j))))
        return
    pool, pals, allowed, errs, hist, written, pics = build(b6, b5, b4, cv)
    write(pool, pals)
    tot = sum(sum(h.values()) for h in hist.values())
    err = sum(errs[k] * sum(hist[k].values()) for k in hist) / tot
    print('pool %d slots, data %d B, mean colour error %.1f/255 (%s)' % (
        SLOTS, data_size(), err, ', '.join('%s %.1f' % (k, errs[k]) for k in sorted(errs))))
    for g, p in enumerate(pals):
        print('  palette %d %s' % (g, ' '.join('%03X' % w for w in p)))
    if '--preview' in sys.argv:
        preview(pool, pals, sys.argv[sys.argv.index('--preview') + 1])
    if '--board' in sys.argv:
        board(pool, pals, pics, sys.argv[sys.argv.index('--board') + 1])



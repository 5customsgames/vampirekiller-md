#!/usr/bin/env python3
"""The spiked ceiling crushers of the stage 6, room 1 (crushers.c) in the 16-bit art (research/gfx16.md, section "Ecraseurs 16 bits").

usage: build_crusher16.py [--preview FILE.png]

Writes sgdk/src/generated/crusher16_md.c/.h: the six cells of the crushers in the layout of vk_stage6_enemy_tiles (patterns
64 68 6C 70 = the chain strip, 16 rows and its first 4, 8 and 12 rows; 74 and 78 = the 32 x 16 body, left and right half; four
tiles per cell, UL LL UR LR) and the PAL2 of that room. The code, the sprite table (actors.c), the hit box (crushers.c) and the
number of tiles of the room load are those of the MSX port: only the picture changes. Castlevania-MD has no such crusher, so it is
drawn here, in the style of its iron: black outline, steel ramp lit from the upper left, rivets, blood on the spike tips.

The chain is a strip of rings with a period of 4 rows (the cut cells 68 6C 70 are the first rows of the full cell 64, so the
pieces join whatever the length of the chain). The body is a riveted bar of 4 rows under the chain end and four spikes of 4 rows,
inside the 12 rows of the MSX body.

PAL2 of the room (vk_crusher16_palette): the room has no other enemy, so the entries other PAL2 content reads (1, 2, 3, 7, 8, 12,
13, 14, 15: objects, key, HUD boxes, text, candle flames) keep the MSX colour of the room; 4, 5, 6 and 9 (the MSX crusher read 4, 6
and 11) take the steel ramp and the blood red; 10 and 11 keep the MSX colour.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'sgdk/src/generated'
sys.path.insert(0, str(ROOT / 'tools'))
import build_enemies16 as be  # noqa: E402

# palette entries of the pictures
ENTRY = {'#': 2,   # outline (222, fixed)
         'd': 4,   # steel shadow (444)
         'm': 13,  # steel (666, fixed)
         's': 5,   # light steel (888)
         'a': 12,  # light (AAA, fixed)
         'l': 6,   # highlight (CCC)
         'w': 14,  # glint (EEE, fixed)
         'r': 9,   # blood (dark red 006)
         '.': 0}
NEW_ENTRIES = {4: 0x0444, 5: 0x0888, 6: 0x0CCC, 9: 0x0006}      # MD colour words (0BGR)

RING = ['.####.',
        '#lasd#',
        '#a..d#',
        '.#dd#.']
SPIKE = ['#lasd#',
         '.#lm#.',
         '..#r#.',
         '...#..']


def chain_rows(n):
    """The n first rows of the chain strip: 6 columns, period 4 rows."""
    return [RING[y % 4] for y in range(n)]


def chain_cell(n):
    """16 x 16 picture: the chain (columns 5 to 10) on the first n rows."""
    out = [[0] * 16 for _ in range(16)]
    for y, row in enumerate(chain_rows(n)):
        for x, ch in enumerate(row):
            out[y][5 + x] = ENTRY[ch]
    return out


def body():
    """32 x 16 picture of the body: the chain end (rows 0 to 3, columns 13 to 18), the bar (rows 4 to 7) and four spikes."""
    rows = [[0] * 32 for _ in range(16)]
    for y, row in enumerate(chain_rows(4)):
        for x, ch in enumerate(row):
            rows[y][13 + x] = ENTRY[ch]
    bar = ['.' + '#' * 30 + '.',
           '#' + ''.join('w' if x in (3, 11, 19, 27) else 'l' if x < 29 else 'a' for x in range(30)) + 'd',
           '#' + ''.join('d' if x in (3, 11, 19, 27) else 'a' if x % 2 else 'm' for x in range(30)) + '#',
           '.' + '#' * 30 + '.']
    for y, row in enumerate(bar):
        for x, ch in enumerate(row):
            rows[4 + y][x] = ENTRY[ch]
    for x0 in (1, 9, 17, 25):
        for y, row in enumerate(SPIKE):
            for x, ch in enumerate(row):
                if ch != '.':
                    rows[8 + y][x0 + x] = ENTRY[ch]
    return rows


def cells():
    """The six cells of the crushers (patterns 64 68 6C 70 74 78), 32 words each."""
    b = body()
    left = [r[:16] for r in b]
    right = [r[16:] for r in b]
    pics = [chain_cell(16), chain_cell(4), chain_cell(8), chain_cell(12), left, right]
    return [be.cell_tiles(p) for p in pics]


def msx_palette():
    t = (GEN / 'rooms.c').read_text()
    allp = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', re.search(r'vk_palettes\[\]\[16\] = \{(.*?)\n\};', t, re.S).group(1))]
    stages = [tuple(int(x) for x in re.findall(r'\d+', e))
              for e in re.findall(r'\{([^{}]*)\}', re.search(r'vk_stages\[18\] = \{(.*?)\};', t, re.S).group(1))]
    i = stages[5][0] + 1                                     # stage 6, room 1
    return allp[i * 16:i * 16 + 16]


def palette():
    pal = msx_palette()
    for i, v in NEW_ENTRIES.items():
        pal[i] = v
    return pal


def write():
    words = [w for c in cells() for w in c]
    pal = palette()
    (GEN / 'crusher16_md.h').write_text('\n'.join([
        '/* Generated by tools/build_crusher16.py (research/gfx16.md). */', '#ifndef VK_CRUSHER16_MD_H', '#define VK_CRUSHER16_MD_H',
        '#include <genesis.h>',
        '/* The six cells of the crushers of the stage 6 room 1 in the layout of vk_stage6_enemy_tiles: patterns 64 68 6C 70 74 78, i.e.',
        ' * tiles 24h to 3Bh of that block, four tiles per cell. */',
        '#define VK_CRUSHER16_FIRST_TILE 0x24', '#define VK_CRUSHER16_TILES 24',
        'extern const u32 vk_crusher16_tiles[%d];' % len(words),
        '/* PAL2 of that room: the MSX room palette, entries 4, 5, 6 and 9 hold the steel ramp and the blood of the crushers. */',
        'extern const u16 vk_crusher16_palette[16];', '#endif', '']))
    (GEN / 'crusher16_md.c').write_text('\n'.join([
        '/* Generated by tools/build_crusher16.py. */', '#include "crusher16_md.h"',
        'const u32 vk_crusher16_tiles[%d] = {\n%s\n};' % (len(words), be.fmt(words, 8)),
        'const u16 vk_crusher16_palette[16] = {\n%s\n};' % be.fmt(pal, 4), '']))
    return len(words) * 4 + 32


def preview(path):
    from PIL import Image
    pal = palette()
    rgb = [(0, 0, 0)] + [(((p >> 1) & 7) * 36, ((p >> 5) & 7) * 36, ((p >> 9) & 7) * 36) for p in pal[1:]]
    chain = chain_cell(16)
    b = body()
    S = 8
    im = Image.new('RGB', (S * 80, S * 40), (90, 20, 40))
    for k in range(3):                                      # three crushers at three heights
        ox = 4 + k * 26
        for y in range(40):
            for x in range(6):
                v = chain[y % 16][5 + x]
                if v and y < 12 + 6 * k:
                    im.paste(rgb[v], (S * (ox + 13 + x), S * y, S * (ox + 14 + x), S * (y + 1)))
        oy = 12 + 6 * k
        for y in range(16):
            for x in range(32):
                if b[y][x]:
                    im.paste(rgb[b[y][x]], (S * (ox + x), S * (oy + y), S * (ox + x + 1), S * (oy + y + 1)))
    im.save(path)


def main():
    print('crusher16: %d B of data (tiles and palette)' % write())
    if '--preview' in sys.argv:
        preview(sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()

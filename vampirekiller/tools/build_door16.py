#!/usr/bin/env python3
"""The door bar of the hall room 7 (item_view.c draw_door, stage 1) in the 16-bit art (research/gfx16.md, section "Barreau de porte 16 bits").

usage: build_door16.py [--preview FILE.png]

Writes sgdk/src/generated/door16_md.c/.h: vk_door16_rows[96], the SAME layout as vk_door_bar_rows (door_key_md.c: 48 rows of two 8-pixel
words, 16 x 48 pixels), loaded by the same code (draw_door shifts the rows up by the lift and blanks what is below), drawn with the same
palette line as before (VK_PAL_OBJ, PAL2 in 16-bit mode), so the opening costs what it cost and no palette entry changes. The MSX bar is a
pink shaft with three knobs (rows 2 to 6, 18 to 22 and 41 to 45, a notch in their last row) and an empty last row; the knobs and the
length are kept, the picture is an iron bar: black outline, steel lit from the left, riveted collars, in the entries 2, 13, 12 and 14 of
PAL2 that every stage 1 palette holds with the same colour (222, 444, AAA, EEE in the hall room 7).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'sgdk/src/generated'
sys.path.insert(0, str(ROOT / 'tools'))
import build_enemies16 as be  # noqa: E402

ENTRY = {'#': 2, 'm': 13, 'a': 12, 'w': 14, '.': 0}
ROWS = 48
SHAFT = '#waam#'                              # columns 5 to 10
COLLAR = ['.######.',                         # columns 4 to 11, five rows
          '#waaaam#',
          '#wa#amm#',
          '#aaammm#',
          '.######.']
COLLARS = (2, 18, 41)                          # first row of the collars, as in the MSX bar
CAP = '######'


def picture():
    img = [[0] * 16 for _ in range(ROWS)]
    for y in range(ROWS - 1):
        for x, ch in enumerate(SHAFT):
            img[y][5 + x] = ENTRY[ch]
    for x in range(6):
        img[0][5 + x] = ENTRY['#']                 # top cap
        img[ROWS - 2][5 + x] = ENTRY["#"]          # bottom cap: the MSX bar ends at row 46, row 47 is empty
    for y0 in COLLARS:
        for dy, row in enumerate(COLLAR):
            for x, ch in enumerate(row):
                img[y0 + dy][4 + x] = ENTRY[ch]
    return img


def words(img):
    return [sum(img[y][c * 8 + x] << (28 - 4 * x) for x in range(8)) for y in range(ROWS) for c in range(2)]


def msx_rows():
    return be.nums((GEN / 'door_key_md.c').read_text(), 'vk_door_bar_rows')


def write():
    w = words(picture())
    (GEN / 'door16_md.h').write_text('\n'.join([
        '/* Generated by tools/build_door16.py (research/gfx16.md). Same layout as vk_door_bar_rows (door_key_md.h). */',
        '#ifndef VK_DOOR16_MD_H', '#define VK_DOOR16_MD_H', '#include <genesis.h>',
        '/* The 16 x 48 door bar of the hall room 7 in the 16-bit art, PAL2 entries 2, 13, 12 and 14. */',
        'extern const u32 vk_door16_rows[%d];' % len(w), '#endif', '']))
    (GEN / 'door16_md.c').write_text('\n'.join([
        '/* Generated by tools/build_door16.py. */', '#include "door16_md.h"',
        'const u32 vk_door16_rows[%d] = {\n%s\n};' % (len(w), be.fmt(w, 8)), '']))
    return len(w) * 4


def preview(path):
    from PIL import Image
    rgb = {0: None, 2: (34, 34, 34), 13: (68, 68, 68), 12: (170, 170, 170), 14: (238, 238, 238)}
    S = 8
    img = picture()
    im = Image.new('RGB', (S * 40, S * 50), (20, 20, 20))
    for ox, lift in ((2, 0), (22, 14)):
        for y in range(ROWS):
            sy = y + lift
            for x in range(16):
                v = img[sy][x] if sy < ROWS else 0
                if v:
                    im.paste(rgb[v], (S * (ox + x), S * (y + 1), S * (ox + x + 1), S * (y + 2)))
    im.save(path)


def main():
    print('door16: %d B of data' % write())
    if '--preview' in sys.argv:
        preview(sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()

def msx_cell(ty, p):
    return B.Msx.cell(pool_words(), slot_map()[(ty, p)])


def laid(js):
    res = []
    for j in js:
        cw, ch = j['size']
        ref = B.ref_box(B.canvas_of([(x, y, msx_cell(ty, p)) for ty, p, x, y in j['ref']]))
        res.append((j, B.place(j['img'], cw, ch, ref, j['mode']), ref))
    return res


def iou(a, b):
    """Overlap of the pictures `a` (canvas of colours or None) and `b` (MSX box rows of indices): for --orient."""
    sa = {(x, y) for y, r in enumerate(a) for x, p in enumerate(r) if p is not None}
    sb = {(x, y) for y, r in enumerate(b) for x, p in enumerate(r) if p}
    return len(sa & sb) / max(1, len(sa | sb))


# ---- palettes --------------------------------------------------------------------------------------------------

ALL_COLOURS = [(r, g, b) for r in range(8) for g in range(8) for b in range(8)]


def err_of(colours, cents):
    return sum(k * min(B.dist(c, q) for q in cents) ** .5 for c, k in colours.items())


def descend(free, objective):
    """Free entries moved to any of the 512 MD colours while the objective goes down."""
    best = objective(free)
    improved = True
    while improved:
        improved = False
        for i in range(len(free)):
            for c in ALL_COLOURS:
                if c in free:
                    continue
                t = free[:]
                t[i] = c
                v = objective(t)
                if v < best - 1e-9:
                    free, best, improved = t, v, True
    return free, best


def greedy(n, objective, pool):
    free = []
    for _ in range(n):
        free.append(min((c for c in pool if c not in free), key=lambda c: (objective(free + [c]), c)))
    return free


def optimise(n, objective, colours):
    if n == 0:
        return [], objective([])
    return descend(greedy(n, objective, sorted(colours)), objective)


def histograms(pics):
    """{kind: {colour: pixels}} over the cells written (each cell once)."""
    hist, seen = {}, set()
    for j, img, ref in pics:
        for ty, p, x, y in j['cells']:
            if (ty, p) in seen:
                continue
            seen.add((ty, p))
            h = hist.setdefault(j['kind'], {})
            for row in img[y:y + 16]:
                for c in row[x:x + 16]:
                    if c is not None:
                        h[c] = h.get(c, 0) + 1
    return hist


@functools.lru_cache(maxsize=None)
def fixed_colours():
    """{entry: MSX colour} of the fixed entries but 7, the same in every room (checked), and entry 7 of each class."""
    info = room_info()
    first = next(iter(info.values()))[0]
    for p, cl, kinds in info.values():
        assert [p[i] for i in B.FIXED if i != VARIABLE] == [first[i] for i in B.FIXED if i != VARIABLE], 'fixed colours differ'
    return {i: first[i] for i in B.FIXED if i != VARIABLE}


def build_palettes(pics):
    """Palettes [class] of 16 words and the table of allowed entries per kind. Layout of the free entries FREE:
    the first n_s are S (shared by the classes 0 and 1: the skeleton's), the others R_c of the class."""
    hist = histograms(pics)
    info = room_info()
    classes_of = {}
    for p, cl, kinds in info.values():
        for k in kinds:
            classes_of.setdefault(k, set()).add(cl)
    fixed = fixed_colours()
    cent = {i: B.lvl(w) for i, w in fixed.items()}
    seven = {c: B.lvl(ENTRY7[c]) for c in range(CLASSES)}
    shared = {k for k, cs in classes_of.items() if len(cs) > 1}
    assert shared == {'skel'} and classes_of == {'skel': {0, 1}, 'rsk': {0}, 'flea': {1}, 'axe': {2}}, classes_of
    base = [cent[i] for i in sorted(cent)]
    best = None
    for n_s in range(0, 6):
        sk = lambda f: err_of(hist['skel'], base + list(f))
        S, _ = optimise(n_s, sk, hist['skel'])
        R = {}
        for kind, c in (('rsk', 0), ('flea', 1)):
            fx = base + [seven[c]] + S
            R[c], _ = optimise(len(FREE) - n_s, lambda f: err_of(hist[kind], fx + list(f)), hist[kind])
        # S once more with the others in view (their R fixed)
        def joint(f):
            return (err_of(hist['skel'], base + list(f)) + err_of(hist['rsk'], base + [seven[0]] + list(f) + R[0]) +
                    err_of(hist['flea'], base + [seven[1]] + list(f) + R[1]))
        if n_s:
            S, _ = descend(S, joint)
            for kind, c in (('rsk', 0), ('flea', 1)):
                fx = base + [seven[c]] + S
                R[c], _ = optimise(len(FREE) - n_s, lambda f: err_of(hist[kind], fx + list(f)), hist[kind])
        tot = joint(S)
        if best is None or tot < best[0]:
            best = (tot, n_s, S, R)
    tot, n_s, S, R = best
    axe_free, _ = optimise(len(FREE), lambda f: err_of(hist['axe'], base + [seven[2]] + list(f)), hist['axe'])
    pals, allowed = [], {}
    for c in range(CLASSES):
        pal = [0] * 16
        for i, w in fixed.items():
            pal[i] = w
        pal[VARIABLE] = ENTRY7[c]
        free = axe_free if c == 2 else S + R[c]
        for i, col in zip(FREE, free):
            pal[i] = B.word(col)
        pals.append(pal)
    shared_idx = set(FREE[:n_s])
    fx_idx = set(fixed)
    allowed['skel'] = [(0, sorted(fx_idx | shared_idx)), (1, sorted(fx_idx | shared_idx))]
    allowed['rsk'] = [(0, sorted(fx_idx | {VARIABLE} | set(FREE)))]
    allowed['flea'] = [(1, sorted(fx_idx | {VARIABLE} | set(FREE)))]
    allowed['axe'] = [(2, sorted(fx_idx | {VARIABLE} | set(FREE)))]
    errs = {k: err_of(hist[k], [B.lvl(pals[allowed[k][0][0]][i]) for i in allowed[k][0][1]]) / sum(hist[k].values())
            for k in hist}
    return pals, allowed, errs, hist, n_s


def to_index(pal, c, idx):
    return min(idx, key=lambda i: (B.dist(B.lvl(pal[i]), c), i))


# ---- cells -----------------------------------------------------------------------------------------------------

def build(b5):
    pics = laid(jobs(b5))
    pals, allowed, errs, hist, n_s = build_palettes(pics)
    words = pool_words()
    smap = slot_map()
    pool = [[0] * 32 for _ in range(SLOTS)]
    for s in range(SLOTS):
        pool[s] = words[s * 32:s * 32 + 32]
    for s in range(4):
        pool[s] = [0] * 32                          # the stage 12 dragon: block 4's own cells
    pool[4], pool[5] = C16.blob_b_cells()           # object 1B (stage 14 rooms 1, 4: slots 4, 5): the 16-bit blob (build_candle16.py)
    written = {}
    for j, img, ref in pics:
        cls, idx = j_palette(j, allowed)
        for ty, p, x, y in j['cells']:
            rows = [[0 if img[y + dy][x + dx] is None else to_index(pals[cls], img[y + dy][x + dx], idx)
                     for dx in range(16)] for dy in range(16)]
            tiles = B.cell_tiles(rows)
            assert written.get((ty, p), tiles) == tiles, 'cell %d %02X written twice with other pixels' % (ty, p)
            written[(ty, p)] = tiles
            pool[smap[(ty, p)]] = tiles
        for ty, p in j['blanks']:
            assert written.get((ty, p), [0] * 32) == [0] * 32, 'cell %d %02X blank and drawn' % (ty, p)
            written[(ty, p)] = [0] * 32
            pool[smap[(ty, p)]] = [0] * 32
    # a pool slot shared by several (type, pattern): the 16-bit contents must agree
    by_slot = {}
    for key, s in smap.items():
        if key in written:
            assert by_slot.setdefault(s, written[key]) == written[key], ('slot %d shared with other pixels' % s, key)
    return pool, pals, allowed, errs, hist, n_s, written


def j_palette(j, allowed):
    """(class, allowed entries) a job's pixels are quantised with; the skeleton is quantised for class 0 and 1 together."""
    cls, idx = allowed[j['kind']][0]
    return cls, idx



@functools.lru_cache(maxsize=None)
def late_tables():
    t = T4.late_text()
    rooms = [tuple(map(int, x.split(','))) for x in
             re.findall(r'\{(\d+,\d+,\d+,\d+)\}', re.search(r'late_graphics_rooms\[7\]\[12\]=\{(.*?)\};', t).group(1))]
    cells = [tuple(map(int, x.split(','))) for x in
             re.findall(r'\{(\d+,\d+,\d+)\}', re.search(r'late_graphics_cells\[\]=\{(.*?)\};', t).group(1))]
    slots = [int(x) for x in re.search(r'late_graphics_slots\[\]=\{(.*?)\};', t).group(1).split(',')]
    return rooms, cells, slots


@functools.lru_cache(maxsize=None)
def enemy_rooms():
    """{(stage, room): [(type, pattern, slot)]} of the rooms of stages 13 to 15 that load cells."""
    rooms, cells, slots = late_tables()
    out = {}
    for s in (13, 14, 15):
        for r in range(12):
            first, tiles, cf, n = rooms[(s - 12) * 12 + r]
            if tiles:
                sl = slots[first:first + tiles // 4]
                out[(s, r)] = [(ty, p, sl[c]) for ty, p, c in cells[cf:cf + n]]
    return out


@functools.lru_cache(maxsize=None)
def slot_map():
    """{(type, pattern): slot} over the rooms of stages 13 to 15 (checked: one slot per cell)."""
    where = {}
    for lst in enemy_rooms().values():
        for ty, p, slot in lst:
            assert where.setdefault((ty, p), slot) == slot, (ty, p)
    return where


@functools.lru_cache(maxsize=None)
def msx_palettes():
    t = (GEN / 'rooms.c').read_text()
    m = re.search(r'vk_palettes\[\]\[16\] = \{(.*?)\n\};', t, re.S)
    allp = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
    st = re.search(r'vk_stages\[18\] = \{(.*?)\};', t, re.S)
    stages = [tuple(int(x) for x in re.findall(r'\d+', e)) for e in re.findall(r'\{([^{}]*)\}', st.group(1))]
    return lambda s, r: allp[(stages[s - 1][0] + r) * 16:(stages[s - 1][0] + r) * 16 + 16]


@functools.lru_cache(maxsize=None)
def room_info():
    """{(stage, room): (MSX palette, class, set of enemy kinds)}; class = index of entry 7 in ENTRY7."""
    pal = msx_palettes()
    rooms = enemy_rooms()
    info = {}
    for (s, r), lst in rooms.items():
        p = pal(s, r)
        info[(s, r)] = (p, ENTRY7.index(p[VARIABLE]), {KIND[ty] for ty, _, _ in lst if ty in KIND})
    return info


ENTRY7 = (0xCAE, 0x66C, 0x26C)


def room_class(stage, room):
    return room_info()[(stage, room)][1]



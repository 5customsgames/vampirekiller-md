def jobs(b5):
    """[dict(name, img, mode, size, cells=[(type, pattern, x, y)], blanks=[(type, pattern)], ref, kind)]

    `img` is laid on the canvas against the MSX picture of `ref` (composite of the layers, default `cells` + `blanks` at the
    place of the cell they pair with); `cells` receive the picture, `blanks` are written blank (second layer)."""
    out = []

    def job(name, img, mode, size, ty, cells, blanks=(), kind=None, ref=None, crop=True):
        if crop:
            img = B.crop(img)
        cs = [(ty, p, x, y) for p, x, y in cells]
        bl = [(ty, p) for p in blanks]
        # reference: the written cells plus their blank partner (the other MSX layer sits at the same place)
        rf = ref or cs + [(ty, p, x, y) for p, (_, x, y) in zip(blanks, cells * 2)]
        out.append(dict(name=name, img=img, mode=mode, size=size, cells=cs, blanks=bl, ref=rf, kind=kind or KIND[ty]))

    def both(name, img, mode, size, ty, left, right, **kw):
        job(name, img, mode, size, ty, left[0], left[1], crop=True, **kw)
        job(name + ' R', B.mirror(B.crop(img)), mode, size, ty, right[0], right[1], crop=False, **kw)

    def column(base):
        """16 x 32 pose of a late type 09 / 10: top cell N (+ layer N + 4), bottom cell N + 8 (+ layer N + 12)."""
        return ([(base, 0, 0), (base + 8, 0, 16)], [base + 4, base + 12])

    # raw 09, skeleton that rises (red skeleton): 21 22 (cells 40, 50) match the picture as it is, 23 24 (60, 70) its mirror
    for k, (left, right) in enumerate(((0x40, 0x60), (0x50, 0x70))):
        both('rsk%d' % k, b5.sprite('b5_rsk%d' % k), 'feet', (16, 32), 22, column(left), column(right))
    # the pile that rises: 26 (flat, first), 25 (higher, last 12 frames before it stands up)
    job('rsk_pile', B.mirror(b5.sprite('b5_rsk_down')), 'feet', (16, 16), 22, [(0x88, 0, 0)], [0x8C])
    job('rsk_rise', B.mirror(b5.sprite('b5_rsk_fall1')), 'feet', (16, 16), 22, [(0x80, 0, 0)], [0x84])
    # raw 10, axe knight (24 x 32 picture on a 16 x 32 pose): poses 5F 60 face left, 61 62 right
    for k, (left, right) in enumerate(((0x40, 0x60), (0x50, 0x70))):
        both('axek%d' % k, AXE[k](b5), 'feet', (16, 32), 20, column(left), column(right))
    # raw 6D, its axe: four rotation poses, 16 x 16
    for k, base in enumerate((0x80, 0x88, 0x90, 0x98)):
        job('kaxe%d' % k, b5.sprite('b5_kaxe%d' % k), 'centre', (16, 16), 21, [(base, 0, 0)], [base + 4])
    # the balls of the first frames (pose 3): the cell F0 of the bone and of the axe
    job('ball_bone', I.sphere(BALL['bone'], 8), 'centre', (16, 16), 13, [(0xF0, 0, 0)], kind='skel')
    job('ball_axe', I.sphere(BALL['axe'], 8), 'centre', (16, 16), 21, [(0xF0, 0, 0)])
    # raw 0B, white skeleton: 47 48 face left, 49 4A face right (as blocks 3)
    for k, (left, right) in enumerate(((0x64, 0x74), (0x6C, 0x7C))):
        both('skel%d' % k, b5.sprite('b5_skel%d' % k), 'feet', (16, 32), 11, ([(left, 0, 0), (left + 4, 0, 16)], []),
             ([(right, 0, 0), (right + 4, 0, 16)], []))
    # raw 04, its bone: 4B upright, 4C /, 4D \ (the same cells in both directions)
    for k, p in enumerate((0x98, 0x9C, 0xA0)):
        job('bone%d' % k, b5.sprite('b5_bone%d' % k), 'centre', (16, 16), 13, [(p, 0, 0)])
    # raw 0D, flea: 67 / 6A stand, 68 / 6B jump
    both('flea_stand', b5.sprite('b5_flea_stand'), 'feet', (16, 16), 14, ([(0x80, 0, 0)], []), ([(0x88, 0, 0)], []))
    both('flea_jump', b5.sprite('b5_flea_jump'), 'feet', (16, 16), 14, ([(0x84, 0, 0)], []), ([(0x8C, 0, 0)], []))
    return out


def lum(c):
    return 3 * c[0] + 4 * c[1] + 2 * c[2]


def squeeze(img, x0=2, w=22, out=16):
    """The 24 x 32 picture of the axe knight (shield on its left, columns 2 to 23) on 16 columns: each output column takes the
    colour of the source column at its centre, so the shield stays whole and complete (it was cut by a crop of 16 columns)."""
    res = [[None] * out for _ in range(len(img))]
    for y, row in enumerate(img):
        for j in range(out):
            c = row[min(len(row) - 1, int(x0 + (j + .5) * w / out))]
            if c is None and any(v is not None for v in row[int(x0 + j * w / out):int(x0 + (j + 1) * w / out + .999)]):
                c = next(v for v in row[int(x0 + j * w / out):int(x0 + (j + 1) * w / out + .999)] if v is not None)
            res[y][j] = c
    return res


EDGE = (5, 5, 6)                             # light lilac of the picture, for the dark pixels of the outline
EDGE_MAX = 21                                # luminance (3r + 4g + 2b) under which an outline pixel is made light


def light_edge(img):
    """The dark pixels on the outer edge of the silhouette become EDGE: the knight stands out on the dark red curtains of the
    stage 15 (and on the dark walls of stages 17 and 18)."""
    h, w = len(img), len(img[0])
    out = [r[:] for r in img]
    for y in range(h):
        for x in range(w):
            p = img[y][x]
            if p is not None and lum(p) < EDGE_MAX and any(
                    not (0 <= y + dy < h and 0 <= x + dx < w) or img[y + dy][x + dx] is None
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = EDGE
    return out


def axe_crop(k, x0=None):
    return lambda b5: light_edge(squeeze(b5.sprite('b5_axek%d' % k)))



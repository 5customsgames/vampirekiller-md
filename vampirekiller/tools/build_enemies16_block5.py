#!/usr/bin/env python3
"""Common enemies of block 5 (stages 13 to 15, not the stage 15 boss) in the 16-bit art (research/gfx16.md, section
"Ennemis 16 bits (bloc 5)").

usage: build_enemies16_block5.py <castlevania-md checkout> [--preview FILE.png] [--orient]

Same method as tools/build_enemies16_block4.py: the code, the sprite table, the hit boxes and the VRAM cells stay those of the
MSX port, only the picture of the cells changes. Stages 13 to 15 use the late enemy system (late_graphics.inc, generated by
tools/build_late_graphics.py): a room loads the pool cells of its enemies, one transfer per run of consecutive pool slots
(`late_graphics_slots`). The 16-bit pictures are stored in an array indexed by that same pool slot (vk_enemy16b5_cells: slot N
is the 128 bytes at 128 * N; slots 0 to 3, the stage 12 dragon, stay blank: it has its own cells in block 4), so the room
loads the same slots with the same transfers from this array instead of late_graphics_words: same tile count, same frames.

- Late enemy types (`internal` type of the cell, SAT in enemies.c, EnemySprite):
    raw 09 (internal 22)  skeleton that rises from a pile of bones (red skeleton of Castlevania-MD)
                          awake: 16 x 32 (top cell + bottom cell, two layers each: patterns N, N + 4 at the same place)
                          poses 21 22 (cells 40 / 48, 50 / 58) and 23 24 (60 / 68, 70 / 78); asleep 26 then 25: 16 x 16,
                          cells 88 / 8C and 80 / 84 (the pile that rises)
    raw 0B (internal 11)  white skeleton (stage 7 to 9 "hopper"): poses 47 48 left (64 / 68, 6C / 70), 49 4A right (74 / 78,
                          7C / 80), 16 x 32, two layers composed in each cell
    raw 04 (internal 13)  its bone: poses 4B 4C 4D = cells 98 9C A0, pose 3 = the ball F0 of the first frames
    raw 0D (internal 14)  flea: 67 68 (left) 6A 6B (right) = cells 80 84 88 8C
    raw 10 (internal 20)  axe knight: 16 x 32, four poses 5F 60 61 62 = cells 40, 50, 60, 70 (+ 8, as raw 09)
    raw 6D (internal 21)  its axe: poses 63 .. 66 = cells 80 88 90 98 (layers N, N + 4), pose 3 = the ball F0 of the 24
                          frames before the axe flies
    object 1B (internal 15, stage 14 rooms 1 and 4, slots 4 and 5): kept MSX (the blob of the candles of object 15).
- Pictures: Castlevania-MD block 5 (src/block5.c: b5_rsk0/1, b5_rsk_fall1, b5_rsk_down, b5_skel0/1, b5_bone0/1/2,
  b5_flea_stand/jump, b5_axek0/1, b5_kaxe0..3), the balls are the 8 x 8 spheres of blocks 2 to 4. Facing left like the MSX
  left cells; the right cells are their mirror. The two MSX layers of a cell become one (N, the picture) and a blank one (N + 4).
- Palette: as in blocks 1 to 4 the entries other PAL2 content reads (1, 2, 3, 7, 8, 12, 13, 14, 15) keep their MSX colour. Entry
  7 is CAE (stage 13 rooms 0 4 7 8 9 10 and stage 14 room 3), 66C (stage 13 rooms 1 2 3 5 6 11) or 26C (stages 14 and 15):
  one palette per class. A skeleton cell is shared between the CAE and 66C rooms, so the skeleton uses no entry 7 and its
  free entries (the first N_SHARED) are the same in both palettes; the other cells of a class (red skeleton in CAE rooms, flea
  in 66C rooms) use the remaining free entries of that class, the axe knight rooms (26C) have all of them.
"""
